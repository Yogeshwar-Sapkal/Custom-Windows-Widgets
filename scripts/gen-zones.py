#!/usr/bin/env python3
"""Generate src/zones.js from the system IANA tz database (zone.tab + iso3166.tab)."""
import json, sys
from pathlib import Path

tz_dir = Path(sys.argv[1] if len(sys.argv) > 1 else "/usr/share/zoneinfo")
countries = {}
for line in (tz_dir / "iso3166.tab").read_text(encoding="utf-8").splitlines():
    if line and not line.startswith("#"):
        code, name = line.split("\t", 1)
        countries[code] = name

zones = []
for line in (tz_dir / "zone.tab").read_text(encoding="utf-8").splitlines():
    if not line or line.startswith("#"):
        continue
    parts = line.split("\t")
    code, tz = parts[0], parts[2]
    city = tz.split("/", 1)[1].replace("_", " ").replace("/", " - ")
    zones.append({"id": tz, "city": city, "country": countries.get(code, code)})

zones.sort(key=lambda z: (z["city"], z["country"]))
out = Path(__file__).resolve().parent.parent / "src" / "zones.js"
out.write_text(
    "// Generated by scripts/gen-zones.py from the IANA tz database. Do not edit.\n"
    "window.ZONES = " + json.dumps(zones, ensure_ascii=False, separators=(",", ":")) + ";\n",
    encoding="utf-8",
)
print(f"wrote {len(zones)} zones to {out}")
